let idiomaActual = localStorage.getItem('cn-idioma') || 'es';
const ORIGINALES = new WeakMap();

function nodosTexto(raiz) {
  const walker = document.createTreeWalker(raiz, NodeFilter.SHOW_TEXT, {
    acceptNode(n) {
      const p = n.parentElement;
      if (!p || p.closest('script,style')) return NodeFilter.FILTER_REJECT;
      return n.textContent.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  const nodos = [];
  let n;
  while ((n = walker.nextNode())) nodos.push(n);
  return nodos;
}

export function aplicarIdioma(idioma) {
  idiomaActual = idioma;
  localStorage.setItem('cn-idioma', idioma);
  document.documentElement.lang = idioma;

  nodosTexto(document.body).forEach(nodo => {
    if (!ORIGINALES.has(nodo)) ORIGINALES.set(nodo, nodo.textContent);
    const original = ORIGINALES.get(nodo);
    const trim = original.trim();
    const prefijo = original.slice(0, original.indexOf(trim));
    const sufijo  = original.slice(original.indexOf(trim) + trim.length);
    const trad = idioma === 'en' ? (TRAD_EN[trim] || trim) : trim;
    nodo.textContent = prefijo + trad + sufijo;
  });

  document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
    if (!el.dataset.esPlaceholder) el.dataset.esPlaceholder = el.getAttribute('placeholder') || '';
    const original = el.dataset.esPlaceholder;
    el.setAttribute('placeholder', idioma === 'en' ? (TRAD_EN[original] || original) : original);
  });

  const btn = document.getElementById('nav-idioma-btn');
  if (btn) btn.textContent = idioma === 'en' ? '🌐 ES' : '🌐 EN';
}

export function toggleIdioma() {
  aplicarIdioma(idiomaActual === 'en' ? 'es' : 'en');
}

export function idiomaGuardado() {
  return idiomaActual;
}

export function traducir(texto) {
  return idiomaActual === 'en' ? (TRAD_EN[texto] || texto) : texto;
}

// Nombre/descripción de producto: usa la versión en inglés que el admin
// haya escrito a mano (nom_en / descripcion_en); si no existe, cae de
// vuelta al texto en español en vez de dejarlo vacío.
export function nombreProducto(p) {
  if (idiomaActual === 'en' && p.nom_en) return p.nom_en;
  return p.nom || '';
}

export function descripcionProducto(p) {
  if (idiomaActual === 'en' && p.descripcion_en) return p.descripcion_en;
  return p.descripcion || '';
}
